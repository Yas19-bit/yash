import java.util.HashSet;
public class Hashsetexample{
    public static void main(String[] args) {
        //unorder 
        HashSet<String> fruits=new HashSet<>();
        fruits.add("dogs");
        fruits.add("cat");
        fruits.add("bull");
        fruits.add("cow");
    
        System.out.println("fruits:"+fruits);
    }
}