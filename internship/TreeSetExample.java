import java.util.TreeSet;

public class TreeSetExample {
    public static void main(String[] args) {
        // Create a TreeSet
        TreeSet<String> set = new TreeSet<>();

        // Add elements 
        set.add("Banana");
        set.add("Apple");
        set.add("Cherry");
        set.add("Mango");
        set.add("Pineapple");

        System.out.println("Treeset: " + set);
    }
}
